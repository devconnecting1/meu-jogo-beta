/*
 * Renders a piece of the town to PNG with the REAL drawing code, under Node.
 *
 *   npm run render:map -- --preset all --out docs/art/after          # the preset scenes + the overview
 *   npm run render:map -- --preset street --out /tmp/x --no-art       # force the flat fallback
 *   npm run render:map -- --x 9000 --y 7000 --w 1280 --h 800 --hour 22 --out /tmp/night.png
 *   npm run render:map -- --compare docs/art/before docs/art/after --out docs/art/compare
 *   npm run render:map -- --preset signs --out docs/art/signs/after   # every building type's sign, night, overview
 *   PZ_SRC=/path/to/other/src node tools/render-map.mjs ...           # render another checkout's code
 *
 * Options: --seed (town seed, default DESIGN.TOWN_SEED), --x --y --w --h (world rect, units), --scale (px per
 * unit, default 1), --hour (0-24, or day / dusk / night), --out (a .png, or a folder for presets), --preset
 * (street, downtown, park, school, gas, gas-night, wreck, campus, campus-quad, campus-night, street-night, overview, or
 * all; signs: sign-<type> for every building type, signs-night, signs-overview and downtown), --no-actors, --no-art,
 * --art <dir>
 * (the local PNGs the "after" renders sample, default design/world-art), --src <dir> (same as PZ_SRC), --hand <id>
 * and --gun <id> (EQUIPS ids the survivor holds and wears at night: 13 flashlight, 15 torchlight, 6 night vision --
 * lit by the game's own rule, shared/sim/survivorLight.ts, LUZ-04), --aim <degrees> (where the survivor faces).
 *
 * How it works: the town is generated by shared/game/world.ts `generateTown`, drawn by client/view/worldView.ts
 * through shared/engine/renderer.ts onto a fake Roblox GUI tree (tools/fake-gui.mjs), exactly as the client
 * does every frame; the zombies and the survivor go through client/view/humanoidView.ts and survivorView.ts, and
 * the night through the renderer's LightMap with the clock's own darkness (shared/sim/clock.ts darkAlphaAt).
 * What the renderer left VISIBLE in the tree -- Frames with their UICorner and UIStroke, the ImageLabels it
 * shows (Stretch, Tile, Slice, ImageRectOffset, ImageColor3, Pixelated) and the light map's gradient strips --
 * is then rasterised by the small software rasteriser below, in ZIndex order. Nothing is re-implemented: if the
 * drawing code changes, the picture changes.
 *
 * With world art present (src/client/view/worldArt.ts), the render hands the view "local:<name>" ids, which the
 * rasteriser reads from design/world-art/<name>.png: the "after" images show the real art before any upload.
 * On an older checkout without that module the town is simply drawn flat, which is what the "before" set is.
 */
