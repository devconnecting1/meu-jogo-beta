/** the first building of `type`, preferring one that faces south (its sign reads the way the camera looks) */
function landmarkOf(world, type) {
	const all = world.solids.filter(s => s.kind === "building" && s.buildingType === type);
	return all.find(s => s.doorSide === "bottom") ?? all[0];
}

/**
 * The 3000 x 2000 piece of town (drawn at half scale) whose frame holds the entrances of the most kinds of
 * building that are not houses: the overview of the signs.
 */
function findSignsOverview(world) {
	const shops = world.solids.filter(s => s.kind === "building" && s.buildingType >= 3);
	let best;
	let bestScore = -Infinity;
	for (let cy = 1400; cy < world.height - 1400; cy += 250) {
		for (let cx = 1900; cx < world.width - 1900; cx += 250) {
			const r = sceneAround(cx, cy, 3000, 2000);
			const inner = { x: r.x + 150, y: r.y + 150, w: r.w - 300, h: r.h - 300 };
			const types = {};
			let doors = 0;
			for (const s of shops) {
				if (!inRect(inner, s.doorX ?? s.x + s.w / 2, s.doorY ?? s.y + s.h)) continue;
				types[s.buildingType === 8 ? 7.5 : s.buildingType] = true;
				doors++;
			}
			const score = Object.keys(types).length * 10 + Math.min(doors, 12);
			if (score > bestScore) {
				bestScore = score;
				best = r;
			}
		}
	}
	return best;
}

