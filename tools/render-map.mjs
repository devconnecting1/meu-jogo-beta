function hourOf(v, fallback) {
	if (v === undefined) return fallback;
	if (v === "day") return 10;
	if (v === "dusk") return 19;
	if (v === "night") return 22;
	return Number(v);
}

function lotAt(world, x, y) {
	return world.lots.find(l => x >= l.x && x < l.x + l.w && y >= l.y && y < l.y + l.h);
}

function inRect(r, x, y) {
	return x >= r.x && x < r.x + r.w && y >= r.y && y < r.y + r.h;
}

/** what a point of the town is made of, for placing the actors of a scene */
function surfaceAt(world, x, y) {
	if (buildingAt(world, x, y) !== undefined) return "building";
	if (pointInSolid(world, x, y, 26) !== undefined) return "solid";
	for (const road of world.roads) {
		if (!inRect(road, x, y)) continue;
		for (const m of road.medians) if (inRect(m, x, y)) return "median";
		return "road";
	}
	const lot = lotAt(world, x, y);
	if (lot === undefined) return "border";
	for (const g of lot.ground) if (inRect(g, x, y)) return g.kind;
	for (const p of lot.paths) if (inRect(p, x, y)) return "dirt";
	if (inRect(lot.yard, x, y)) return lot.zone === "commercial" ? "plaza" : "grass";
	return "sidewalk";
}

/** first point of a spiral around (cx, cy), inside `rect`'s inner part, on one of `kinds`, away from `taken` */
function place(world, rect, cx, cy, kinds, taken) {
	const inset = 90;
	for (let i = 0; i < 4000; i++) {
		const a = i * 2.39996;
		const d = 14 * Math.sqrt(i) * 3;
		const x = Math.round(cx + Math.cos(a) * d);
		const y = Math.round(cy + Math.sin(a) * d);
		if (x < rect.x + inset || y < rect.y + inset || x > rect.x + rect.w - inset || y > rect.y + rect.h - inset)
			continue;
		if (!kinds.includes(surfaceAt(world, x, y))) continue;
		if (taken.some(p => Math.hypot(p.x - x, p.y - y) < 150)) continue;
		taken.push({ x, y });
		return { x, y };
	}
	return undefined;
}

function isParked(s) {
	if (s.heading === undefined) return true;
	const q = s.heading / (Math.PI / 2);
	return Math.abs(q - Math.round(q)) < 0.01;
}

function solidsIn(world, r) {
	return querySolids(world, r.x, r.y, r.x + r.w, r.y + r.h, []);
}

function sceneAround(cx, cy, w, h) {
	return { x: Math.round(cx - w / 2), y: Math.round(cy - h / 2), w, h };
}

const W = 1280;
const H = 800;

/** how much of the rect `s` covers inside `r` (0..1 of s) */
function visibleShare(s, r) {
	const w = Math.max(0, Math.min(s.x + s.w, r.x + r.w) - Math.max(s.x, r.x));
	const h = Math.max(0, Math.min(s.y + s.h, r.y + r.h) - Math.max(s.y, r.y));
	return (w * h) / Math.max(1, s.w * s.h);
}

function junctionsIn(world, r) {
	return world.junctions.filter(j => j.x < r.x + r.w && j.x + j.w > r.x && j.y < r.y + r.h && j.y + j.h > r.y).length;
}

/** a residential street mid-block: parked cars, street trees, houses with their front yards on one side */
function findStreet(world) {
	let best;
	let bestScore = -Infinity;
	for (const road of world.roads) {
		if (road.avenue || road.vertical) continue;
		const mid = road.y + road.h / 2;
		for (let t = road.x + 900; t < road.x + road.w - 900; t += 128) {
			const up = lotAt(world, t, road.y - 300);
			const down = lotAt(world, t, road.y + road.h + 300);
			if (up === undefined || down === undefined) continue;
			if (
				up.zone !== "residential" ||
				down.zone !== "residential" ||
				up.kind !== "block" ||
				down.kind !== "block"
			) {
				continue;
			}
			for (const dy of [-230, 230]) {
				const r = sceneAround(t, mid + dy, W, H);
				const list = solidsIn(world, r);
				const cars = list.filter(s => s.tags === "car" && isParked(s)).length;
				const wrecks = list.filter(s => s.tags === "car" && !isParked(s)).length;
				const trees = list.filter(s => s.kind === "tree").length;
				let houses = 0;
				for (const s of list) {
					if (s.kind === "building" && (s.buildingType === 1 || s.buildingType === 2))
						houses += visibleShare(s, r);
				}
				const bins = list.filter(s => s.tags === "trash").length;
				const score =
					3 * Math.min(cars, 4) +
					5 * Math.min(wrecks, 1) +
					Math.min(trees, 7) +
					6 * Math.min(houses, 2) +
					2 * Math.min(bins, 1) -
					12 * junctionsIn(world, r);
				if (score > bestScore) {
					bestScore = score;
					best = r;
				}
			}
		}
	}
	return best;
}

/** a downtown street crossing with its crosswalks and the shops on its corners */
function findDowntown(world) {
	let best;
	let bestScore = -Infinity;
	for (const j of world.junctions) {
		const around = [
			lotAt(world, j.x - 200, j.y - 200),
			lotAt(world, j.x + j.w + 200, j.y - 200),
			lotAt(world, j.x - 200, j.y + j.h + 200),
			lotAt(world, j.x + j.w + 200, j.y + j.h + 200),
		];
		const shops = around.filter(l => l !== undefined && l.zone === "commercial").length;
		if (shops < 3) continue;
		for (const [ox, oy] of [
			[-300, -170],
			[300, -170],
			[-300, 170],
			[300, 170],
		]) {
			const r = sceneAround(j.x + j.w / 2 + ox, j.y + j.h / 2 + oy, W, H);
			const list = solidsIn(world, r);
			let shopArea = 0;
			for (const s of list) if (s.kind === "building" && s.buildingType > 5) shopArea += visibleShare(s, r);
			const cars = list.filter(s => s.tags === "car").length;
			const bins = list.filter(s => s.tags === "trash").length;
			const avenue = world.roads.some(rd => rd.avenue && inRect(rd, j.x + 1, j.y + 1));
			const score = shopArea * 6 + Math.min(cars, 4) + Math.min(bins, 2) - (avenue ? 4 : 0);
			if (score > bestScore) {
				bestScore = score;
				best = r;
			}
		}
	}
	return best;
}

/** a 3000 x 2000 piece of town with the most variety: shops, houses, a park, a gas station, a school */
function findOverview(world) {
	let best;
	let bestScore = -Infinity;
	for (let cy = 2000; cy < world.height - 2000; cy += 500) {
		for (let cx = 2200; cx < world.width - 2200; cx += 500) {
			const r = sceneAround(cx, cy, 3000, 2000);
			const list = solidsIn(world, r);
			// (a plain object: the Luau shims turn Set.size into a method)
			const types = {};
			let houses = 0;
			for (const s of list) {
				if (s.kind !== "building" || visibleShare(s, r) < 0.6) continue;
				types[s.buildingType === 2 ? 1 : s.buildingType] = true;
				if (s.buildingType <= 2) houses++;
			}
			const park = world.lots.some(l => l.kind === "park" && visibleShare(l, r) > 0.35);
			const wrecks = list.filter(s => s.tags === "car" && !isParked(s)).length;
			const score =
				Object.keys(types).length * 4 + Math.min(houses, 6) + (park ? 10 : 0) + Math.min(wrecks, 2) * 2;
			if (score > bestScore) {
				bestScore = score;
				best = r;
			}
		}
	}
	return best;
}

function findPark(world) {
	for (const lot of world.lots) {
		if (lot.kind !== "park" || lot.paths.length < 2) continue;
		const v = lot.paths[0];
		const hz = lot.paths[1];
		return sceneAround(v.x + v.w / 2 + 160, hz.y + hz.h / 2 - 60, W, H);
	}
	return undefined;
}

function findBuilding(world, type) {
	for (const s of world.solids) {
		if (s.kind === "building" && s.buildingType === type) return s;
	}
	return undefined;
}

function findSchool(world) {
	const b = findBuilding(world, 3);
	if (b === undefined) return undefined;
	const lot = lotAt(world, b.x + b.w / 2, b.y + b.h / 2);
	const yard = lot?.ground.find(g => g.kind === "playground");
	const cx = yard !== undefined ? (b.x + b.w / 2 + yard.x + yard.w / 2) / 2 : b.x + b.w / 2;
	const cy = yard !== undefined ? (b.y + b.h / 2 + yard.y + yard.h / 2) / 2 : b.y + b.h / 2;
	return sceneAround(cx, cy, W, H);
}

/**
 * The college campus (DESIGN_RULES EDI-17): its whole block (the four buildings round the quad and the four streets
 * round the block) and a closer frame on the quad, centred on its fountain or statue. Undefined in a town without one.
 */
function findCampus(world) {
	const hall = findBuilding(world, 12);
	if (hall === undefined) return undefined;
	const lot = lotAt(world, hall.x + hall.w / 2, hall.y + hall.h / 2);
	if (lot === undefined) return undefined;
	const centre = world.solids.find(
		s => s.kind === "prop" && (s.tags === "fountain" || s.tags === "statue") && inRect(lot, s.x, s.y),
	);
	const qx = centre !== undefined ? centre.x + centre.w / 2 : lot.x + lot.w / 2;
	const qy = centre !== undefined ? centre.y + centre.h / 2 : lot.y + lot.h / 2;
	return {
		block: sceneAround(lot.x + lot.w / 2, lot.y + lot.h / 2, 2080, 2080),
		quad: sceneAround(qx, qy, W, H),
	};
}

function findGas(world) {
	const b = findBuilding(world, 5);
	if (b === undefined) return undefined;
	const lot = lotAt(world, b.x + b.w / 2, b.y + b.h / 2);
	const apron = lot?.ground.find(
		g => g.kind === "apron" && Math.hypot(g.x + g.w / 2 - b.x - b.w / 2, g.y + g.h / 2 - b.y - b.h / 2) < 900,
	);
	const cx = apron !== undefined ? (b.x + b.w / 2) * 0.35 + (apron.x + apron.w / 2) * 0.65 : b.x + b.w / 2;
	const cy = apron !== undefined ? (b.y + b.h / 2) * 0.35 + (apron.y + apron.h / 2) * 0.65 : b.y + b.h / 2;
	return sceneAround(cx, cy, W, H);
}

/**
 * A car abandoned askew in a lane and broken into, with blood by its door: the same hashes client/view/worldView.ts
 * `drawCarArt` reads (23: its state, 25: the blood), so the "after" picture shows what the game will show.
 */
function findWreck(world) {
	for (const s of world.solids) {
		if (s.tags !== "car" || isParked(s)) continue;
		const roll = hash01(s.x, s.y, 23);
		if (roll < 0.3 || roll >= 0.75 || hash01(s.x, s.y, 25) >= 0.5) continue;
		return sceneAround(s.x + s.w / 2 + 160, s.y + s.h / 2 - 60, W, H);
	}
	return undefined;
}

/** outward unit normal of a building's entrance wall */
function doorNormal(side) {
	if (side === "top") return { x: 0, y: -1 };
	if (side === "left") return { x: -1, y: 0 };
	if (side === "right") return { x: 1, y: 0 };
	return { x: 0, y: 1 };
}

