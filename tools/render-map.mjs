function makeShadow(state) {
	const tmp = { x: 0, y: 0 };
	return (x, y, len) => {
		const t = state.hour;
		if (t > 6 && t < 18) {
			const rad = ((t / 24) * 360 - 225) * (Math.PI / 180);
			tmp.x = Math.cos(rad) * len;
			tmp.y = -Math.sin(rad) * len;
			return tmp;
		}
		const dx = x - state.lightX;
		const dy = y - state.lightY;
		const d = Math.hypot(dx, dy);
		if (d < 1) {
			tmp.x = 0;
			tmp.y = len * 0.5;
		} else {
			tmp.x = (dx / d) * len;
			tmp.y = (dy / d) * len;
		}
		return tmp;
	};
}

