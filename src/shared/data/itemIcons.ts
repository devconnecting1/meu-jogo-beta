/** a category by weapon kind: a weapon row the table has not caught up with */
function weaponFallback(kind: number): string {
	if (kind === WeaponKind.Pistol) return "cat_pistol";
	if (kind === WeaponKind.Rifle) return "cat_rifle";
	if (kind === WeaponKind.MG) return "cat_mg";
	if (kind === WeaponKind.Shotgun) return "cat_shotgun";
	if (kind === WeaponKind.Sniper) return "cat_sniper";
	if (kind === WeaponKind.Bow) return "cat_bow";
	if (kind === WeaponKind.Special) return "cat_stun";
	return "cat_blade";
}

/** a category by equipment slot (EQUIPS kind; the cosmetic kind 4 is an outfit unless it is a pet) */
function equipFallback(kind: number): string {
	if (kind === EquipSlot.Cloth) return "cat_armor";
	if (kind === EquipSlot.Hand) return "cat_nav";
	if (kind === EquipSlot.Gun) return "cat_attach";
	return "cat_outfit";
}

function ref(key: string | undefined, fallback: string): IconRef {
	const k = key !== undefined && ITEM_ICONS[key] !== undefined ? key : fallback;
	return { key: k, own: k.sub(1, 4) !== "cat_" };
}

/**
 * The icon of item `kind` / `id` (ItemKind): its own drawing or its category's, never a letter. An id past the tables
 * (a row added to the data and not to this file) gets the category of its kind.
 */
export function iconOf(kind: number, id: number): IconRef {
	if (kind === ItemKind.Weapon) {
		const w = WEAPONS[id];
		return ref(WEAPON_ICONS[id], w !== undefined ? weaponFallback(w.kind) : "cat_item");
	}
	if (kind === ItemKind.Equip) {
		const e = EQUIPS[id];
		return ref(EQUIP_ICONS[id], e !== undefined ? equipFallback(e.kind) : "cat_item");
	}
	if (kind === ItemKind.Use) {
		const u = USABLES[id];
		// the Bag's own split (client/ui/itemInfo.ts isMedicine): what treats rather than feeds
		const medicine = u !== undefined && (u.pain > 0 || u.speed > 0 || u.calm > 0 || (u.hunger <= 0 && u.hp > 0));
		return ref(USABLE_ICONS[id], medicine ? "cat_medkit" : "cat_meal");
	}
	if (kind === ItemKind.Etc && ETC_ITEMS[id] !== undefined) return ref(ETC_ICONS[id], "cat_item");
	return ref(undefined, "cat_item");
}

/** the glyph of skill `id` (SKILLS) */
export function skillIconOf(id: number): string {
	const key = SKILL_ICONS[id];
	return key !== undefined && ITEM_ICONS[key] !== undefined && SKILLS[id] !== undefined ? key : "cat_item";
}

/** the ItemKind that stands for the skills in iconKeys */
export const SKILL_KIND = 0;

/**
 * Every icon the items of `kind` (ItemKind, or SKILL_KIND) draw, each once: what a view that may show any of them
 * must be able to hold (client/ui/itemIcon.ts maxFrameCount).
 */
export function iconKeys(kind: number): Array<string> {
	const out: Array<string> = [];
	const add = (key: string): void => {
		if (!out.includes(key)) out.push(key);
	};
	if (kind === SKILL_KIND) {
		for (let i = 0; i < SKILLS.size(); i++) add(skillIconOf(i));
		return out;
	}
	let n = ETC_ITEMS.size();
	if (kind === ItemKind.Weapon) n = WEAPONS.size();
	else if (kind === ItemKind.Equip) n = EQUIPS.size();
	else if (kind === ItemKind.Use) n = USABLES.size();
	for (let i = 0; i < n; i++) add(iconOf(kind, i).key);
	return out;
}
