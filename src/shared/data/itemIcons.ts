/*
 * The item icons, as DATA (docs/DESIGN_RULES.md UI-11): what the Bag's tiles, the item card and the HUD hotbar draw
 * instead of the item's initial, so what an item is can be SEEN rather than read.
 *
 * There is no image asset behind them. Each icon is a 16 x 16 grid of characters, one per pixel: "." is empty and
 * every other character is an art colour of shared/engine/colors.ts ICON_ART (a digit or `k` = an outline, s = steel,
 * r = red...). client/ui/itemIcon.ts turns a grid into a few dozen Frames (runs and blocks of one colour, painted in
 * ICON_ART_ORDER so each colour is a handful of rectangles) and reuses them when a tile shows another item.
 *
 * The style they are drawn to (docs/DESIGN_RULES.md ART-13; MON-02: legible at 24 and 32 px; npm run test:icons 7
 * checks the measurable part):
 *  - one light, from the top left: inside every material three tones -- the lit edge, the base, the shadow -- and a
 *    one-pixel shine on metal and glass;
 *  - a 1-pixel outline all around, in a DARKER HUE of the material it surrounds (ICON_OUTLINES: steel's is
 *    blue-black, wood's brown-black, red's maroon...), so every pixel that touches empty space is an outline pixel;
 *    pixel-perfect on the diagonals (a 4-neighbour ring: no doubled corners) and no stray single pixel;
 *  - the same weight: what is drawn is 12-14 pixels on its longest side (75-88 % of the cell), 14 for the long ones;
 *  - melee weapons, bows, arrows and hand tools on the 45-degree diagonal, business end top right; FIREARMS side on,
 *    muzzle right (at 16 px a gun turned 45 degrees reads as a knife: its profile is what tells a pistol from an SMG
 *    from a rifle); food, medicine, materials and buildables upright, front or 3/4.
 *
 * Two kinds of icon:
 *  - an item's OWN icon: every item of Núcleo 1 (CON-03) has one -- Dagger, Axe, Baseball bat, Pistol; raw meat,
 *    cooked meat, apple, canned food, bandage; wood, stone, steel, cloth, normal ammo; campfire, wooden barricade,
 *    wooden door, craft desk; cotton clothes and flashlight;
 *  - a CATEGORY icon (`cat_*`) by kind and subtype for everything else (a katana and a machete share the blade; the
 *    auto pistol is the SMG, the revolver its own; each ammo its casing: brass pistol rounds, red shotgun shells, the
 *    linked machine-gun belt, arrows), so no item falls back to a letter. A new row in a data table that nobody drew
 *    an icon for gets the category of its kind (iconOf's fallbacks) until someone does.
 *
 * The skills have their own glyphs (`skill_*`, some shared with an item: Robin Hood is a bow). ICON_GLYPHS are the
 * small one-colour glyphs the UI paints in a theme colour (the Bag's tabs, the craft stations, the equipped check).
 */
