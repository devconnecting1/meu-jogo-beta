/*
 * The item icons, as DATA (docs/DESIGN_RULES.md UI-11): what the Bag's tiles, the item card and the HUD hotbar draw
 * instead of the item's initial, so what an item is can be SEEN rather than read.
 *
 * There is no image asset behind them. Each icon is a 16 x 16 grid of characters, one per pixel: "." is empty and
 * every other character is an art colour of shared/engine/colors.ts ICON_ART (k = the outline, s = steel, r = red...).
 * client/ui/itemIcon.ts turns a grid into a few dozen Frames (runs and blocks of one colour, painted in
 * ICON_ART_ORDER so each colour is a handful of rectangles) and reuses them when a tile shows another item.
 *
 * The rules they are drawn to (MON-02: legible at 32 px):
 *  - a strong silhouette with a 1-pixel `k` outline, so the icon reads on every tile face -- the dark iron of an
 *    owned item, the lighter iron of an equipped one, the blue of the selection;
 *  - 2-4 colours and a highlight from the top left;
 *  - weapons on the diagonal (the pose everyone reads as "an item"), the rest front or side on.
 *
 * Two kinds of icon:
 *  - an item's OWN icon: every item of Núcleo 1 (CON-03) has one -- Dagger, Axe, Baseball bat, Pistol; raw meat,
 *    cooked meat, apple, canned food, bandage; wood, stone, steel, cloth, normal ammo; campfire, wooden barricade,
 *    wooden door, craft desk; cotton clothes and flashlight;
 *  - a CATEGORY icon (`cat_*`) by kind and subtype for everything else (a katana and a machete share the blade, the
 *    three pistols the revolver...), so no item falls back to a letter. A new row in a data table that nobody drew
 *    an icon for gets the category of its kind (iconOf's fallbacks) until someone does.
 *
 * The skills have their own glyphs (`skill_*`, some shared with an item: Robin Hood is a bow). ICON_GLYPHS are the
 * small one-colour glyphs the UI paints in a theme colour (the Bag's tabs, the craft stations, the equipped check).
 */
