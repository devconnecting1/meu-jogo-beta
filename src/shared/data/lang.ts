const languageMaps: Array<Map<string, string>> = [
	new Map<string, string>(),
	new Map<string, string>(),
	new Map<string, string>(),
	new Map<string, string>(),
];

for (const entry of LANG_TABLE) {
	if (!languageMaps[1].has(entry.key)) {
		languageMaps[1].set(entry.key, entry.korean);
	}
	if (!languageMaps[2].has(entry.key)) {
		languageMaps[2].set(entry.key, entry.chinese);
	}
	if (!languageMaps[3].has(entry.key)) {
		languageMaps[3].set(entry.key, entry.japanese);
	}
}

export function langGet(key: string, langType: number): string {
	if (langType === LangType.English) {
		return key;
	}
	const map = languageMaps[langType];
	if (map !== undefined) {
		const value = map.get(key);
		if (value !== undefined && value !== "") {
			return value;
		}
	}
	return key;
}
