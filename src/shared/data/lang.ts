/**
 * Hand-written corrections, by language, for the few strings the machine gets wrong. Empty by design: add
 * an entry ONLY after seeing the platform translate something badly, and say in a comment what was wrong.
 */
const OVERRIDES: Array<Map<string, string>> = [
	new Map<string, string>(), // English: the source itself, never overridden
	new Map<string, string>(), // Korean
	new Map<string, string>(), // Chinese
	new Map<string, string>(), // Japanese
];

/**
 * The text to show for `key`. Returns the English source unless a manual override exists, because Roblox
 * replaces the rendered text itself -- returning a translation here would fight the platform for the same
 * label and the player would see whichever won the frame.
 */
export function langGet(key: string, langType: number): string {
	const map = OVERRIDES[langType];
	if (map !== undefined) {
		const value = map.get(key);
		if (value !== undefined && value !== "") return value;
	}
	return key;
}
