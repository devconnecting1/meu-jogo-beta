/*
 * Every string the game can show, and the one place a translation may be overridden.
 *
 * This file used to carry Korean, Chinese and Japanese columns inherited from the original game. It does
 * not any more: Roblox translates the experience itself, matching each string by its SOURCE text and
 * swapping it at render time for the language the player's own account is set to. Our keys ARE the English
 * text, so that match is free and no call site had to change.
 *
 * What the table is FOR, then, is being the registry of what may be translated: `npm run locale` exports it
 * to the CSV that the Localization tab imports (design/locale/ProjectZ.csv). A string that is shown but not
 * listed here never reaches that table, so it is the one language nobody can fix -- which is exactly what
 * had happened to nineteen strings from the onboarding and the end-of-run screen before this pass.
 *
 * OVERRIDES is deliberately empty. Machine translation of a one- or two-word game string guesses, and it
 * will get one wrong eventually ("Round" is a magazine, not a shape). When it does, the fix goes here, for
 * that language and that key only, and the rest keeps coming from the platform.
 */

